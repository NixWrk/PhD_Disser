def replace_nb(nb):
    for i,(old,new) in enumerate(R,1):
        count = sum(c.cell_type == "markdown" and c.source.count(old) for c in nb.cells)
        if count == 0 and any(c.cell_type == "markdown" and new in c.source for c in nb.cells):
            continue
        assert count == 1, f"notebook: replacement {i} matched {count}"
        for c in nb.cells:
            if c.cell_type == "markdown":
                c.source = c.source.replace(old,new)

def cell_text(cell):
    return " ".join(cell.get_text(" ", strip=True).split())

def table_md(table):
    rows = []
    for tr in table.find_all("tr"):
        cells = tr.find_all(["th","td"], recursive=False)
        if not cells:
            continue
        row = []
        for cell in cells:
            row.append(cell_text(cell).replace("|", r"\|"))
            row.extend([""] * (int(cell.get("colspan",1)) - 1))
        rows.append(row)
    if not rows:
        return ""
    width = max(map(len,rows))
    rows = [row + [""]*(width-len(row)) for row in rows]
    number = re.compile(r"^[+\-−]?(?:\d+(?:[.,]\d*)?|[.,]\d+)(?:[eE][+\-−]?\d+)?%?$")
    align = [all(not row[j] or number.fullmatch(row[j]) for row in rows[1:]) for j in range(width)]
    lines = ["| " + " | ".join(rows[0]) + " |",
             "| " + " | ".join("---:" if align[j] else "---" for j in range(width)) + " |"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows[1:])
    return "\n".join(lines)

def reader_from_dom(nb, html_text):
    soup = BeautifulSoup(html_text, "html.parser")
    all_tables = soup.find_all("table")
    dom_tables = soup.select("div.jp-OutputArea-output table")
    ti = 0
    parts = []
    for c in nb.cells:
        if c.cell_type == "markdown":
            parts.append(c.source)
            continue
        for o in c.get("outputs",[]):
            d = o.get("data",{})
            if "text/markdown" in d:
                parts.append("".join(d["text/markdown"]))
            elif "text/html" in d and "<table" in d["text/html"]:
                assert ti < len(dom_tables), "missing table in canonical HTML DOM"
                parts.append(table_md(dom_tables[ti]))
                ti += 1
    assert ti == len(dom_tables), f"consumed {ti} DOM tables, found {len(dom_tables)}"
    reader = "\n\n".join(x for x in parts if x.strip()) + "\n"
    return reader, {"canonical_html_dom_tables":len(all_tables),
                    "canonical_html_output_tables":len(dom_tables),
                    "reader_tables_converted":ti, "reader_parts":len(parts),
                    "reader_chars":len(reader), "reader_lines":len(reader.splitlines())}

def main():
    baseline = nbformat.read(BEFORE, as_version=4)
    nb = nbformat.read(NOTEBOOK, as_version=4)
    assert_code_unchanged(nb, baseline)
    GENERATOR.write_text(replace_text(GENERATOR.read_text(encoding="utf-8"), "generator"), encoding="utf-8")
    replace_nb(nb)
    code_status = assert_code_unchanged(nb, baseline)
    nbformat.write(nb, NOTEBOOK)
    exp = HTMLExporter()
    exp.exclude_input = True
    exp.exclude_input_prompt = True
    exp.exclude_output_prompt = True
    html_text, _ = exp.from_notebook_node(nb)
    HTML.write_text(html_text, encoding="utf-8")
    reader, reader_status = reader_from_dom(nb, html_text)
    READER.write_text(reader, encoding="utf-8")
    result = {"code_status":code_status, "notebook_sha256":file_sha(NOTEBOOK),
              "html_sha256":file_sha(HTML), "reader_sha256":file_sha(READER), **reader_status}
    print(json.dumps(result, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    main()
