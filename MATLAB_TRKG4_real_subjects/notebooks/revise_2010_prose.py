def _get(cell, key, default=None):
    if hasattr(cell, "get"):
        return cell.get(key, default)
    return getattr(cell, key, default)


def _set(cell, key, value):
    try:
        cell[key] = value
    except (TypeError, AttributeError):
        setattr(cell, key, value)


def _source(cell) -> str:
    value = _get(cell, "source", "")
    return "".join(value) if isinstance(value, list) else str(value)


def _set_source(cell, value: str) -> None:
    _set(cell, "source", value)


def _cells(nb) -> MutableSequence:
    cells = _get(nb, "cells")
    if cells is None:
        raise TypeError("Notebook must expose a cells sequence")
    return cells


def _is_markdown(cell) -> bool:
    return _get(cell, "cell_type") == "markdown"


def _is_code(cell) -> bool:
    return _get(cell, "cell_type") == "code"


def _find_cell(cells: Iterable, predicate: Callable[[object, str], bool]):
    for cell in cells:
        src = _source(cell)
        if predicate(cell, src):
            return cell
    return None


def _new_markdown_cell(source: str, key: str):
    try:
        from nbformat.v4 import new_markdown_cell

        cell = new_markdown_cell(source=source)
    except Exception:  # pragma: no cover - fallback for minimal notebook stubs
        cell = {"cell_type": "markdown", "metadata": {}, "source": source}
    stable_id = "revise-2010-" + re.sub(r"[^a-zA-Z0-9-]+", "-", key).strip("-")
    _set(cell, "id", stable_id[:64])
    metadata = _get(cell, "metadata", {}) or {}
    metadata = dict(metadata)
    metadata[MARKER_PREFIX] = {"module_version": MODULE_VERSION, "key": key}
    _set(cell, "metadata", metadata)
    return cell


def _caption_marker_in_source(source: str) -> bool:
    return source.lstrip().startswith(f"<!-- {MARKER_PREFIX}:figure:")


def _ensure_caption_after(cells: MutableSequence, selector: Callable[[object, str], bool], key: str, caption: str) -> bool:
    """Insert or refresh one caption cell immediately after its figure cell."""
    target = _find_cell(cells, selector)
    if target is None:
        return False

    marker = _caption_marker(key)
    caption_source = marker + "\n\n" + caption.strip() + "\n"
    target_index = cells.index(target)
    existing_index = None
    existing = None
    for index, cell in enumerate(cells):
        if marker in _source(cell):
            existing_index, existing = index, cell
            break

    if existing is not None:
        _set_source(existing, caption_source)
        metadata = dict(_get(existing, "metadata", {}) or {})
        metadata[MARKER_PREFIX] = {"module_version": MODULE_VERSION, "key": key}
        _set(existing, "metadata", metadata)
        # Keep the order of several captions belonging to one output cell.
        # If the caption is already in the contiguous caption block, refreshing
        # its text is sufficient and avoids reversing 11.5.2/11.5.3.
        if existing_index > target_index and all(
                _caption_marker_in_source(_source(cell))
                for cell in cells[target_index + 1:existing_index]):
            return True
        cells.pop(existing_index)
        if existing_index < target_index:
            target_index -= 1
    else:
        existing = _new_markdown_cell(caption_source, key)

    insertion_index = target_index + 1
    while insertion_index < len(cells) and _caption_marker_in_source(_source(cells[insertion_index])):
        insertion_index += 1
    cells.insert(insertion_index, existing)
    return True


def _output_text(output) -> str:
    pieces = []
    data = _get(output, "data", {}) or {}
    for value in data.values() if hasattr(data, "values") else []:
        pieces.append("".join(value) if isinstance(value, list) else str(value))
    value = _get(output, "text", "")
    pieces.append("".join(value) if isinstance(value, list) else str(value))
    return "\n".join(pieces)


def _markdown_output(text: str):
    import nbformat as nbf

    return nbf.v4.new_output(
        "display_data",
        data={
            "text/markdown": text,
            "text/plain": "<IPython.core.display.Markdown object>",
        },
        metadata={},
    )


