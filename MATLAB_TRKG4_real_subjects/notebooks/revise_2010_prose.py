def _remove_generated_caption_cells(cells: MutableSequence, keys: Iterable[str]) -> int:
    """Remove caption cells made by an older version of this module."""
    keyset = set(keys)
    kept = []
    removed = 0
    for cell in cells:
        metadata = _get(cell, "metadata", {}) or {}
        record = metadata.get(MARKER_PREFIX) if hasattr(metadata, "get") else None
