def cross_table(out=OUT):
    out=Path(out);bank=KernelBank.__new__(KernelBank)
    with np.load(out/'kernel.local.npz') as a:
        bank.h=a['h'];bank.q=a['q'];bank.f=a['f'];bounds=a['bounds']
    rows=[]
    for case in read(out/'results.local.json'):
        with np.load(out/(case['key']+'.npz')) as a:y=a['observations']
        four=bounded_fit(y[:4],bank,bounds,np.arange(4));pred=four['prediction_ohm'][-1]
        cross=next(i for i,item in enumerate(case['assemblies']) if item['record_id'].endswith('006') and 'горизонтальная' in item['label'])
        for index,name in [(4,'Основной ряд, запись 004'),(cross,'Горизонтальная ось креста, запись 006')]:
            replacement=y[:5].copy();replacement[-1]=y[index]
            f=bounded_fit(replacement,bank,bounds)
            rows.append({'История подключения':HISTORIES[case['channel']],'Дыхание':STATES[case['state']],
                'Вариант 140 мм':name,'Z₁₄₀, Ом':y[index],
                'Прогноз 140 мм по 60–120 мм, Ом':pred,
                'Ошибка прогноза, Ом':pred-y[index],
                'Невязка пяти размеров, %':f['residual_percent']})
    return pd.DataFrame(rows)


def observation_table(out=OUT):
    rows=[]
    for case in read(Path(out)/'results.local.json'):
        with np.load(Path(out)/(case['key']+'.npz')) as a:y=a['observations']
        for item,value in zip(case['assemblies'],y):
            rows.append({'История подключения':HISTORIES[case['channel']],'Дыхание':STATES[case['state']],
                'Сборка и запись':item['label'],'Поле BEI':item['channel'],
                'Медиана Z, Ом':value,'Основной размерный ряд':item['reference']})
    return pd.DataFrame(rows)


