def file_sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def protected(cell):
    return json.dumps({"source": cell.get("source",""), "outputs": cell.get("outputs",[])},
                      ensure_ascii=False, sort_keys=True, separators=(",",":"))

def assert_code_unchanged(now, old):
    a = [c for c in now.cells if c.cell_type == "code"]
    b = [c for c in old.cells if c.cell_type == "code"]
    assert len(a) == len(b) == 16
    sources = all(x.source == y.source for x,y in zip(a,b))
    outputs = all(protected(x) == protected(y) for x,y in zip(a,b))
    assert sources and outputs, "code source/output changed"
    return {"code_cells":16, "code_sources_unchanged":sources, "code_outputs_unchanged":outputs,
            "computational_execution":"not_run_by_instruction"}

