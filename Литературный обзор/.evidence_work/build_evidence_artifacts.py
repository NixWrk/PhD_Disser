def load_metadata() -> dict[str, dict]:
    with urllib.request.urlopen(API_ITEMS, timeout=30) as response:
        items = json.load(response)
    return {item["key"]: item["data"] for item in items}


def author_label(source: dict) -> str:
    authors = source.get("authors") or []
    if not authors:
        return "Без автора"
    first = authors[0].get("lastName") or authors[0].get("name") or "Без автора"
    return f"{first} et al." if len(authors) > 1 else first


def year_of(source: dict) -> str:
    match = re.search(r"(?:19|20)\d{2}", source.get("date", ""))
    return match.group(0) if match else "б. г."


def classify(source: dict) -> tuple[str, str]:
    title = source["title"].casefold()
    if any(token in title for token in ("guideline", "consensus", "monitoring", "overview", "advances")):
        return "Клинический контекст мониторинга", "рекомендации/обзор"
    if any(token in title for token in ("meta-analysis", "systematic review")):
        return "Сводная валидность методов", "систематический обзор/метаанализ"
    if any(token in title for token in ("review", "revisited", "principles", "theory", "equation", "methodological")):
        return "Теория и методология ИКГ", "методологический обзор/теоретическая работа"
    if any(token in title for token in ("ejection fraction", "ventricular function", "systolic time")):
        return "Оценка систолической функции и ФВ", "сравнительное исследование"
    if any(token in title for token in ("infant", "neonate", "children", "pediatric", "paediatric", "preterm")):
        return "Педиатрическая и неонатальная валидизация", "сравнительное исследование"
    return "Валидизация сердечного выброса у взрослых", "сравнительное/валидационное исследование"


