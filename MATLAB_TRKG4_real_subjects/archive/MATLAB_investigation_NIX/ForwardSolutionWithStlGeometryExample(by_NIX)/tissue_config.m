function cfg = tissue_config()
%TISSUE_CONFIG Configuration for multi-STL EIT forward calculations.
% Conductivities are frequency-dependent and are calculated from IT'IS
% Tissue Properties Database V5.0 / Gabriel dielectric coefficients.

cfg.input_mode = 'stl_surfaces';
cfg.frequency_hz = 50e3;
cfg.itis_database = 'ITIS Tissue Properties Database V5.0';

cfg.body_stl = first_existing_stl({ ...
    fullfile('output', 'prepared', 'YAROSLAV_BODY_resampled_3mm_meshfix.stl'), ...
    fullfile('stl', 'body.stl'), ...
    fullfile('stl', 'raw', 'YAROSLAV_BODY.stl'), ...
    'YAROSLAV_BODY.stl'});
cfg.mesh_fineness = 'moderate'; % very_coarse, coarse, moderate, fine, very_fine
cfg.mesher = 'gmsh'; % netgen or gmsh
cfg.gmsh_mesh_size = 25;
cfg.show_figures = true;
cfg.use_parallel_assignment = true;
cfg.parallel_workers = 'auto';
cfg.reuse_mesh_cache = true;
cfg.mesh_cache_file = fullfile('output', 'stl_body_mesh_cache.mat');

cfg.n_electrodes = 16;
cfg.electrode_height_fraction = 0.5;
cfg.electrode_area = pi * 10^2 / 4 * 0.9;
cfg.z_contact = 2.5e-7 * 0.05 / (pi * 0.01^2 / 4);

% Replace [] with measured Nx3 electrode centres when available.
cfg.electrode_centres_xyz = [];

sigma_soft = itis_conductivity('Muscle', cfg.frequency_hz);
sigma_heart = itis_conductivity('Heart Muscle', cfg.frequency_hz);
sigma_lung = itis_conductivity('Lung (Inflated)', cfg.frequency_hz);
sigma_bone = itis_conductivity('Bone (Cortical)', cfg.frequency_hz);
sigma_blood = itis_conductivity('Blood', cfg.frequency_hz);

% Default background for elements not inside a specific tissue STL.
cfg.background.name = 'soft_tissue';
cfg.background.itis_name = 'Muscle';
cfg.background.sigma = sigma_soft;

% Internal closed STL surfaces. Later entries override earlier ones if masks overlap.
cfg.required_tissues = {'lungs', 'bones', 'blood'};
cfg.tissues = struct('name', {}, 'file', {}, 'itis_name', {}, 'sigma', {}, 'enabled', {});
cfg.tissues(end+1) = tissue_entry('heart', ...
    first_existing_stl({fullfile('stl', 'heart.stl')}), ...
    'Heart Muscle', sigma_heart);
cfg.tissues(end+1) = tissue_entry('lungs', ...
    first_existing_stl({ ...
    fullfile('output', 'prepared', 'YAROSLAV_LUNGS_resampled_3mm_meshfix.stl'), ...
    fullfile('output', 'prepared', 'YAROSLAV_LUNGS_prepared_ascii.stl'), ...
    fullfile('stl', 'lungs.stl'), ...
    fullfile('stl', 'raw', 'YAROSLAV_LUNGS.stl'), ...
    'YAROSLAV_LUNGS.stl'}), ...
    'Lung (Inflated)', sigma_lung);
cfg.tissues(end+1) = tissue_entry('lung_left', ...
    first_existing_stl({fullfile('stl', 'lung_left.stl')}), ...
    'Lung (Inflated)', sigma_lung);
cfg.tissues(end+1) = tissue_entry('lung_right', ...
    first_existing_stl({fullfile('stl', 'lung_right.stl')}), ...
    'Lung (Inflated)', sigma_lung);
cfg.tissues(end+1) = tissue_entry('bones', ...
    first_existing_stl({ ...
    fullfile('output', 'prepared', 'YAROSLAV_BONES_resampled_3mm_meshfix.stl'), ...
    fullfile('output', 'prepared', 'YAROSLAV_BONES_prepared_ascii.stl'), ...
    fullfile('stl', 'bones.stl'), ...
    fullfile('stl', 'raw', 'YAROSLAV_BONES.stl'), ...
    'YAROSLAV_BONES.stl'}), ...
    'Bone (Cortical)', sigma_bone);
cfg.tissues(end+1) = tissue_entry('blood', ...
    first_existing_stl({ ...
    fullfile('output', 'prepared', 'YAROSLAV_BLOOD_resampled_3mm_meshfix.stl'), ...
    fullfile('output', 'prepared', 'YAROSLAV_BLOOD_prepared_ascii.stl'), ...
    fullfile('stl', 'blood.stl'), ...
    fullfile('stl', 'raw', 'YAROSLAV_BLOOD.stl'), ...
    'YAROSLAV_BLOOD.stl'}), ...
    'Blood', sigma_blood);
end

function tissue = tissue_entry(name, file, itis_name, sigma)
tissue = struct( ...
    'name', name, ...
    'file', file, ...
    'itis_name', itis_name, ...
    'sigma', sigma, ...
    'enabled', true);
end

function filename = first_existing_stl(candidates)
filename = '';
for i = 1:numel(candidates)
    if isfile(candidates{i})
        filename = candidates{i};
        return;
    end
end
end
