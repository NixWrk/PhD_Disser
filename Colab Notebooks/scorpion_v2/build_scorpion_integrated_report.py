def montage_name(record_number):
    n = int(record_number)
    if n in (1, 2, 3, 4):
        return f'ТТРКГ {"2×2" if n == 3 else "1×4" if n == 4 else "1×1"} + боковая 140 мм'
    if n == 5:
        return 'ТТРКГ 1×4? + боковая 140 мм, перпендикулярная ось'
    if n in (6, 11):
        return f'Боковой крест {140 if n == 6 else 60} мм'
    if 7 <= n <= 10:
        return f'Боковая {dict(zip(range(7, 11), [120, 100, 80, 60]))[n]} мм + ТТРКГ 1×1? / 1×4?'
    if 12 <= n <= 17:
        return f'ТЕПС-{n - 10} + ТТРКГ 1×1'
    return 'АЕПС + ТТРКГ 1×1'


