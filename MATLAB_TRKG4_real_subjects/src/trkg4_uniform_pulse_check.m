function result=trkg4_uniform_pulse_check(K0,C,baseline,max_delta_Z,P)
% Direct CEM checks at both ends of the observed centred pulse range.
% Geometry and finite contact impedance are fixed at their baseline values.
rho=baseline.rho_apparent_ohm_m;s=baseline.dZ_dlogrho_ohm;
assert(isfinite(max_delta_Z)&&max_delta_Z>0&&isfinite(s)&&s>0);
dr=rho*max_delta_Z/s;assert(dr>0&&dr<rho);
if nargin<5,P=[1,0;0,1;0,-1;-1,0];end
z=zeros(2,1);points=struct([]);
for j=1:2
    shift=(2*j-3)*dr;r=rho+shift;
    [T,J,qc]=trkg4_lateral_cem_response(K0/r,C,{K0},r,P,1,1);
    z(j)=T(2,1);linear=baseline.predicted_Z_ohm+s*shift/rho;
    point=struct('rho_ohm_m',r,'delta_rho_ohm_m',shift,'Z_ohm',z(j),...
        'linear_Z_ohm',linear,'error_relative_to_max_pulse',abs(z(j)-linear)/max_delta_Z,...
        'dZ_dlogrho_ohm',J(2,1,1),'qc',qc);
    if isempty(points),points=point;else,points(end+1)=point;end
end
fd=(z(2)-z(1))/(2*dr);adjoint=s/rho;
derivative_error=abs(fd/adjoint-1);linearity_error=max([points.error_relative_to_max_pulse]);
assert(all(diff(z)>0),'Nonmonotonic local homogeneous response');
result=struct('rho0_ohm_m',rho,'max_observed_abs_delta_Z_ohm',max_delta_Z,...
    'checked_delta_rho_ohm_m',dr,'points',points,...
    'finite_difference_dZ_drho_per_m',fd,'adjoint_dZ_drho_per_m',adjoint,...
    'finite_difference_relative_error',derivative_error,...
    'max_linearity_error_relative_to_max_pulse',linearity_error,...
    'linearity_error_limit',1e-3,'derivative_error_limit',1e-4,...
    'passed',linearity_error<=1e-3&&derivative_error<=1e-4,...
    'status','numerical_check_only_not_physical_validation');
end
