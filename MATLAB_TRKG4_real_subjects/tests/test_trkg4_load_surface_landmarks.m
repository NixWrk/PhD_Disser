function payload = localValidPayload()
    payload = struct( ...
        'coordinate_system', 'surface_path_v1', ...
        'units', 'mm', ...
        'source_basename', 'body_surface.stl', ...
        'right_guide_points_xyz_mm', [1 2 3; 4 5 6], ...
        'left_guide_points_xyz_mm', [7 8 9; 10 11 12; 13 14 15]);
end

function json_text = localJsonWithPoints(right_points, left_points)
    json_text = ['{"coordinate_system":"surface_path_v1",' ...
        '"units":"mm",' ...
        '"source_basename":"body_surface.stl",' ...
        '"right_guide_points_xyz_mm":', right_points, ',' ...
        '"left_guide_points_xyz_mm":', left_points, '}'];
end

function json_file = localWriteJson(test_case, json_text)
    json_file = [tempname, '.json'];
    file_identifier = fopen(json_file, 'w', 'n', 'UTF-8');
    if file_identifier < 0
        error('test_trkg4_load_surface_landmarks:FileCreateFailed', ...
            'Не удалось создать временный JSON-файл.');
    end
    fwrite(file_identifier, json_text, 'char');
    fclose(file_identifier);
    addTeardown(test_case, @() localDeleteFile(json_file));
end

function localDeleteFile(json_file)
    if isfile(json_file)
        delete(json_file);
    end
end
