def verify(out=OUT):
    out=Path(out);contract=read(out/'input_contract.local.json')
    for name,digest in read(out/'manifest.local.json')['outputs'].items():
        if sha(out/name)!=digest:raise ValueError('Changed surface input: '+name)
    if sha(FOLDER/'lateral_solution_surfaces.py')!=contract['producer_sha256']:
        raise ValueError('Surface producer changed')
    for name,digest in contract['dependencies'].items():
        if sha(FOLDER/name)!=digest:raise ValueError('Changed dependency: '+name)
    if sha(ROOT/'MATLAB_TRKG4_real_subjects/configs/tissue_literature_v2.json')!=contract['registry_sha256']:
        raise ValueError('Material registry changed')
    summary_path=EXPERIMENT/'derived/scorpion_review/summary.local.json'
    if sha(summary_path)!=contract['review_summary_sha256'] or sha(EXPERIMENT/'annotations/scorpion_review/annotations_candidates.local.json')!=contract['annotations_sha256']:
        raise ValueError('Signal summary or annotations changed')
    records=read(summary_path)['records']
    for entry in contract['provenance']:
        record=next(r for r in records if r['record_id']==entry['record_id'] and r['fs_hz_scenario']==entry['working_fs_hz'])
        if sha(EXPERIMENT/record['source_relative_path'])!=entry['source_sha256'] or sha(EXPERIMENT/'derived/scorpion_review'/(record['key']+'.npz'))!=entry['npz_sha256']:
            raise ValueError('Recorded signal or cache changed')
    return contract


