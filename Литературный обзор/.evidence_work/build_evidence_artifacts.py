def write_bibliography(manifest: dict, metadata: dict[str, dict]) -> None:
    lines = ["# Библиографический список", "", "В список включены 59 уникальных источников из библиотеки Zotero. Записи расположены сначала по фамилии первого автора, затем по году публикации.", ""]
    sorted_sources = sorted(manifest["sources"], key=lambda source: (author_label(source).casefold(), year_of(source), source["title"].casefold()))
    for index, source in enumerate(sorted_sources, start=1):
        lines.append(f"{index}. {citation(source, metadata)} `Zotero:{source['zotero_key']}`")
    (WORKSPACE / "06_Библиография_корпуса.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    try:
        metadata = load_metadata()
        (ROOT / "zotero_metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    except Exception:
        cached = ROOT / "zotero_metadata.json"
        metadata = json.loads(cached.read_text(encoding="utf-8")) if cached.exists() else {}
    cards = study_cards(manifest, metadata)
    write_cards(cards)
    write_matrix(manifest)
    write_bundle(manifest)
    write_bibliography(manifest, metadata)
    print(json.dumps({"cards": len(cards), "matrix_rows": len(MATRIX), "evidence": len(EVIDENCE), "claims": len(CLAIMS)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
