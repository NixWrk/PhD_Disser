def general_design_recommendations(r):
    cards=r['cards'][r['cards'].stage=='grid5_plus_checks'].copy()
    parsed=cards.montage.str.extract(r'in(?P<d>20|40)_out(?P<l>80|100)_(?P<kind>.+)')
    cards=pd.concat([cards,parsed],axis=1)
    cards[['d','l']]=cards[['d','l']].astype(int)

    def paired_effect(compartment,metric,factor,a,b,keys):
        data=cards[cards.compartment==compartment]
        first=data[data[factor]==a].set_index(keys)[metric]
        second=data[data[factor]==b].set_index(keys)[metric]
        effect=100*(first-second)/second
        return float(effect.median()),float(effect.min()),float(effect.max())

    d_effect={}
    l_effect={}
    cuff_effect={}
    cuff_q_pp={}
    for compartment in PARAMS:
        d_effect[compartment]={metric:paired_effect(compartment,metric,'d',20,40,['l','kind']) for metric in ('min_B','min_Q')}
        l_effect[compartment]={metric:paired_effect(compartment,metric,'l',80,100,['d','kind']) for metric in ('min_B','min_Q')}
        subset=cards[cards.compartment==compartment].set_index(['d','l','kind'])
        cuff_effect[compartment]={}
        for metric in ('min_B','min_Q'):
            wide=subset[metric].xs('wide_cuff_equivalent_area',level='kind')
            narrow=subset[metric].xs('circumferential_ring',level='kind')
            effect=100*(wide-narrow)/narrow
            cuff_effect[compartment][metric]=(float(effect.median()),float(effect.min()),float(effect.max()))
        wide_q=100*subset.min_Q.xs('wide_cuff_equivalent_area',level='kind')
        narrow_q=100*subset.min_Q.xs('circumferential_ring',level='kind')
        pp=wide_q-narrow_q
        cuff_q_pp[compartment]=(float(pp.median()),float(pp.min()),float(pp.max()))

    states=r['states'].copy()
