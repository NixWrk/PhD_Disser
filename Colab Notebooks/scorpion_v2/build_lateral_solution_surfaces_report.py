    payload['sizes']=SIZES.tolist();payload['cases']=read(out/'results.local.json')
    for case in payload['cases']:
        with np.load(out/(case['key']+'.npz')) as a:
            case.update({key:a[key].tolist() for key in a.files})
        case['label']=f"Боковой канал {case['channel']} · {STATES[case['state']].lower()}"
    script=(FOLDER/'solution_surfaces_view.js').read_text(encoding='utf-8')
