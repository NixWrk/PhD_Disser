function [sigma, tissue] = itis_conductivity(tissue_name, frequency_hz)
%ITIS_CONDUCTIVITY Electrical conductivity from IT'IS/Gabriel coefficients.
%   SIGMA = ITIS_CONDUCTIVITY(TISSUE_NAME, FREQUENCY_HZ) returns conductivity
%   in S/m using the IT'IS Tissue Properties Database V5.0 dielectric
%   coefficients and the Gabriel dispersion equation.

if nargin < 2 || isempty(frequency_hz)
    frequency_hz = 50e3;
end

if ~isscalar(frequency_hz) || ~isfinite(frequency_hz) || frequency_hz <= 0
    error('frequency_hz must be a positive scalar.');
end

tissue = itis_dielectric_coefficients(tissue_name);

eps0 = 8.8542e-12;
omega = 2 * pi * frequency_hz;
sigma = tissue.sig;

for k = 1:numel(tissue.del)
    if tissue.del(k) == 0 || tissue.tau_s(k) == 0
        continue;
    end

    alpha = tissue.alpha(k);
    abs_term = (omega * tissue.tau_s(k)) .^ (1 - alpha);
    phase = pi / 2 * (1 - alpha);
    re = 1 + abs_term * cos(phase);
    im = abs_term * sin(phase);
    sigma = sigma + omega * eps0 * tissue.del(k) * im / (re^2 + im^2);
end
end

function tissue = itis_dielectric_coefficients(tissue_name)
% Coefficients copied from:
% IT'IS Foundation, Tissue Properties Database V5.0,
% Thermal_dielectric_acoustic_MR properties_database_V5.0(ASCII).txt.

key = normalize_tissue_name(tissue_name);

switch key
    case {'soft_tissue', 'muscle', 'muscles'}
        tissue = coeff('Muscle', ...
            [50, 7000, 1200000, 25000000], ...
            [7.234e-12, 353.678e-9, 318.31e-6, 2.274e-3], ...
            [0.1, 0.1, 0.1, 0], ...
            0.2);

    case {'heart', 'heart_muscle', 'myocardium'}
        tissue = coeff('Heart Muscle', ...
            [50, 1200, 450000, 25000000], ...
            [7.958e-12, 159.155e-9, 72.343e-6, 4.547e-3], ...
            [0.1, 0.05, 0.22, 0], ...
            0.05);

    case {'lung', 'lungs', 'lung_inflated', 'lung_left', 'lung_right'}
        tissue = coeff('Lung (Inflated)', ...
            [18, 500, 250000, 40000000], ...
            [7.958e-12, 63.662e-9, 159.155e-6, 7.958e-3], ...
            [0.1, 0.1, 0.2, 0], ...
            0.03);

    case {'lung_deflated', 'lungs_deflated'}
        tissue = coeff('Lung (Deflated)', ...
            [45, 1000, 500000, 10000000], ...
            [7.958e-12, 159.155e-9, 159.155e-6, 15.915e-3], ...
            [0.1, 0.1, 0.2, 0], ...
            0.2);

    case {'bone', 'bones', 'bone_cortical', 'cortical_bone'}
        tissue = coeff('Bone (Cortical)', ...
            [10, 180, 5000, 100000], ...
            [13.263e-12, 79.577e-9, 159.155e-6, 15.915e-3], ...
            [0.2, 0.2, 0.2, 0], ...
            0.02);

    case {'bone_cancellous', 'cancellous_bone', 'spongy_bone'}
        tissue = coeff('Bone (Cancellous)', ...
            [18, 300, 20000, 20000000], ...
            [13.263e-12, 79.577e-9, 159.155e-6, 15.915e-3], ...
            [0.22, 0.25, 0.2, 0], ...
            0.07);

    case {'blood'}
        tissue = coeff('Blood', ...
            [56, 5200, 0, 0], ...
            [8.377e-12, 132.629e-9, 159.155e-6, 15.915e-3], ...
            [0.1, 0.1, 0.2, 0], ...
            0.7);

    case {'fat', 'adipose'}
        tissue = coeff('Fat', ...
            [9, 35, 33000, 10000000], ...
            [7.958e-12, 15.915e-9, 159.155e-6, 15.915e-3], ...
            [0.2, 0.1, 0.05, 0.01], ...
            0.035);

    otherwise
        error('Unsupported IT''IS tissue name: %s', tissue_name);
end
end

function tissue = coeff(name, del, tau_s, alpha, sig)
tissue = struct( ...
    'name', name, ...
    'database_version', 'ITIS Tissue Properties Database V5.0', ...
    'model', 'Gabriel dispersion relationship', ...
    'del', del, ...
    'tau_s', tau_s, ...
    'alpha', alpha, ...
    'sig', sig);
end

function key = normalize_tissue_name(tissue_name)
key = lower(strtrim(char(tissue_name)));
key = strrep(key, '(', '');
key = strrep(key, ')', '');
key = strrep(key, '-', '_');
key = strrep(key, ' ', '_');
end
