def ru(value, digits=None):
    """Format a reader-facing number with the Russian decimal separator."""
    if digits is None:
        text = f'{value:g}'
    else:
        text = f'{value:.{digits}f}'
    return text.replace('.', ',')


def ru_sig(value, digits=4):
    return f'{value:.{digits}g}'.replace('.', ',')


