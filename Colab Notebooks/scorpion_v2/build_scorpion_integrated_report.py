def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def saved_output(name, cell_id, expected_sha256):
    """Redisplay an attributed, hash-locked source result, without its old code."""
    from IPython.display import display
    path = FOLDER / name
    if path.parent != FOLDER or sha(path) != expected_sha256:
        raise ValueError('Source notebook changed: ' + name)
    book = nbformat.read(path, as_version=4)
    selected = next(cell for cell in book.cells if cell.id == cell_id)
    if not selected.outputs or any(o.output_type == 'error' for o in selected.outputs):
        raise ValueError('Missing or failed source result: ' + cell_id)
    for output in selected.outputs:
        if output.output_type not in ('display_data', 'execute_result'):
            raise ValueError('Unexpected source output type')
        display(dict(output.data), raw=True, metadata=dict(output.get('metadata', {})))


