def get_artem_radial_at(time_idx: int = 8) -> dict:
    """Вернуть нормированные импедансные данные Artem в момент time_idx.

    Аналог `RadialExpDataArtem[time_]` из IMPdata.m.
    Индексация с 1 (как в Mathematica), диапазон 1..25.

    Параметры
    ---------
    time_idx : int
        Индекс времени (1-based). По умолчанию 8 (пик систолы).

    Возвращает
    ----------
    dict с ключами "dZRad" (np.ndarray, 5,), "zBase", "flDZ", "flBase".
    """
    if not 1 <= time_idx <= len(ARTEM_RADIAL_ARRAY_FIX):
        raise IndexError(f"time_idx={time_idx} выходит за диапазон 1..{len(ARTEM_RADIAL_ARRAY_FIX)}")
    row = ARTEM_RADIAL_ARRAY_FIX[time_idx - 1]
    return {
        "dZRad": row[1:] / 1000.0,   # перевод из мОм в Ом
        "zBase": np.array([70.0, 67.0, 58.0, 67.0, 76.0]),
        "flDZ":  float(row[0]) / 1000.0,
        "flBase": 79.0,
    }
