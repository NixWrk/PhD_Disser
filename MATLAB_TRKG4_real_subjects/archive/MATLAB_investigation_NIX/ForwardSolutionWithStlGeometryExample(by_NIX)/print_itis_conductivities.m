function print_itis_conductivities(frequency_hz)
%PRINT_ITIS_CONDUCTIVITIES Print conductivities used by the STL workflow.

if nargin < 1 || isempty(frequency_hz)
    frequency_hz = 50e3;
end

tissues = { ...
    'Muscle', ...
    'Heart Muscle', ...
    'Lung (Inflated)', ...
    'Lung (Deflated)', ...
    'Bone (Cortical)', ...
    'Bone (Cancellous)', ...
    'Blood', ...
    'Fat'};

fprintf('ITIS/Gabriel conductivities at %.6g Hz:\n', frequency_hz);
for i = 1:numel(tissues)
    [sigma, meta] = itis_conductivity(tissues{i}, frequency_hz);
    fprintf('  %-18s %.6g S/m\n', meta.name, sigma);
end
end
