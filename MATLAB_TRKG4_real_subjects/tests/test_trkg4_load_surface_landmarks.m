function tests = test_trkg4_load_surface_landmarks
%TEST_TRKG4_LOAD_SURFACE_LANDMARKS Tests for the JSON landmark loader.

    tests = functiontests(localfunctions);
end

function setupOnce(test_case)
    source_directory = fullfile( ...
        fileparts(fileparts(mfilename('fullpath'))), 'src');
    path_entries = strsplit(path, pathsep);
    source_was_on_path = any(strcmpi(path_entries, source_directory));
    if ~source_was_on_path
        addpath(source_directory);
    end
    test_case.TestData.source_directory = source_directory;
    test_case.TestData.source_added_by_test = ~source_was_on_path;
end

function teardownOnce(test_case)
    if test_case.TestData.source_added_by_test
        rmpath(test_case.TestData.source_directory);
    end
end

function testValidJsonReturnsCanonicalDoubleMatrices(test_case)
    payload = localValidPayload();
    payload.untrusted_metadata = struct('absolute_path', 'D:\private\scan');
    json_file = localWriteJson(test_case, jsonencode(payload));

    landmarks = trkg4_load_surface_landmarks(json_file);

    verifyClass(test_case, landmarks.right_guide_points_xyz_mm, 'double');
    verifyClass(test_case, landmarks.left_guide_points_xyz_mm, 'double');
    verifySize(test_case, landmarks.right_guide_points_xyz_mm, [2 3]);
    verifySize(test_case, landmarks.left_guide_points_xyz_mm, [3 3]);
    verifyEqual(test_case, landmarks.coordinate_system, 'surface_path_v1');
    verifyEqual(test_case, landmarks.units, 'mm');
    verifyEqual(test_case, landmarks.source_basename, 'body_surface.stl');
    verifyFalse(test_case, isfield(landmarks, 'untrusted_metadata'));
    verifyEqual(test_case, landmarks.right_guide_points_xyz_mm, ...
        [1 2 3; 4 5 6]);
end

function testTtrkgSymmetricContractIsValidatedAndPreserved(test_case)
    payload = localValidPayload();
    payload.schema = 'trkg4_ttrkg_arm_surface_v2';
    payload.modality = 'TTRKG';
    payload.montage = 'four_electrode_arm_surface';
    payload.reference_definition = ...
        'first_resolved_guide_point_at_arm_trunk_boundary_proximal_to_distal';
    payload.electrode_order = ...
        {'I_plus', 'V_plus', 'V_minus', 'I_minus'};
    payload.symmetry = struct('mode', 'equal_path_distances', ...
        'inner_from_reference_mm', 20, 'outer_from_inner_mm', 80);
    json_file = localWriteJson(test_case, jsonencode(payload));

    landmarks = trkg4_load_surface_landmarks(json_file);

    verifyEqual(test_case, landmarks.schema, 'trkg4_ttrkg_arm_surface_v2');
    verifyEqual(test_case, landmarks.modality, 'TTRKG');
    verifyEqual(test_case, landmarks.montage, 'four_electrode_arm_surface');
    verifyEqual(test_case, landmarks.electrode_order, ...
        ["I_plus"; "V_plus"; "V_minus"; "I_minus"]);
    verifyEqual(test_case, landmarks.symmetry.mode, 'equal_path_distances');
    verifyEqual(test_case, landmarks.symmetry.inner_from_reference_mm, 20);
    verifyEqual(test_case, landmarks.symmetry.outer_from_inner_mm, 80);
end

