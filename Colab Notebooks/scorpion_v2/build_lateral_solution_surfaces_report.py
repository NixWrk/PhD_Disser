def fit_table(out=OUT):
    rows=[]
    for case in read(Path(out)/'results.local.json'):
        f=case['fit'];p=f['parameters']
        rows.append({'Боковой канал':case['channel'],'Дыхание':STATES[case['state']],
            'ρ₁, Ом·м':p[0],'ρ₂, Ом·м':p[1],'h, мм':p[2],
            'Относительная невязка, %':f['residual_percent'],
            'Параметры на границе':', '.join(n for n,b in zip(['ρ₁','ρ₂','h'],f['boundary_hits']) if b),
            'κ(J) по логарифмам параметров':float(np.linalg.cond(log_jacobian(p)))})
    return pd.DataFrame(rows)


def stability_plot(out=OUT):
    import plotly.graph_objects as go
    out=Path(out)
    with np.load(out/'kernel.local.npz') as a:h=a['h']
    fig=go.Figure()
    for case in read(out/'results.local.json'):
        with np.load(out/(case['key']+'.npz')) as a:rss=a['profile_rss']
        fig.add_trace(go.Scatter(x=h,y=rss/case['fit']['rss'],mode='lines',
            name=f"Канал {case['channel']}, {STATES[case['state']].lower()}"))
    fig.add_hline(y=1.10,line_dash='dot',annotation_text='Условный прирост RSS 10%')
    fig.update_layout(template='plotly_white',title='Рисунок 4. Минимальная невязка при фиксированной h',
        xaxis_title='h, мм',yaxis_title='RSS(h) / RSSₘᵢₙ',height=480,legend=dict(orientation='h',y=-.2))
    return fig.to_html(full_html=False,include_plotlyjs=False)


def cross_table(out=OUT):
    out=Path(out);bank=KernelBank.__new__(KernelBank)
    with np.load(out/'kernel.local.npz') as a:
        bank.h=a['h'];bank.q=a['q'];bank.f=a['f'];bounds=a['bounds']
    rows=[]
    for case in read(out/'results.local.json'):
        with np.load(out/(case['key']+'.npz')) as a:y=a['observations']
        four=bounded_fit(y[:4],bank,bounds,np.arange(4));pred=four['prediction_ohm'][-1]
        for index,name in [(4,'Основной ряд, запись 004'),(9,'Основная ось креста, запись 006')]:
            replacement=y[:5].copy();replacement[-1]=y[index]
            f=bounded_fit(replacement,bank,bounds)
            rows.append({'Боковой канал':case['channel'],'Дыхание':STATES[case['state']],
                'Вариант 140 мм':name,'Z₁₄₀, Ом':y[index],
                'Прогноз 140 мм по 60–120 мм, Ом':pred,
                'Ошибка прогноза, Ом':pred-y[index],
                'Невязка пяти размеров, %':f['residual_percent']})
    return pd.DataFrame(rows)


def observation_table(out=OUT):
    rows=[]
    for case in read(Path(out)/'results.local.json'):
        with np.load(Path(out)/(case['key']+'.npz')) as a:y=a['observations']
        for item,value in zip(case['assemblies'],y):
            rows.append({'Гипотеза бокового канала':case['channel'],'Дыхание':STATES[case['state']],
                'Сборка и запись':item['label'],'Поле BEI':item['channel'],
                'Медиана Z, Ом':value,'Основной размерный ряд':item['reference']})
    return pd.DataFrame(rows)


